import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
const migrations=readdirSync('supabase/migrations').filter(n=>n.endsWith('.sql')).sort();
const strip=s=>s.replace(/^\s*(begin|commit);\s*$/gmi,'');
const sql=`-- GENERATED by node scripts/build-legacy-upgrade.mjs
-- ORIGINAL UUID SCHEMA ONLY. Stop app writes and take an independent backup first.
-- Run the ENTIRE file as database owner. One transaction; any error rolls everything back.
-- Original tables and IDs are retained in the private previsio_legacy_archive schema.
begin;
${readFileSync('supabase/upgrade/legacy-before.sql','utf8')}
${migrations.map(n=>`-- SOURCE: ${n}\n${strip(readFileSync('supabase/migrations/'+n,'utf8'))}`).join('\n')}
${readFileSync('supabase/upgrade/legacy-after.sql','utf8')}
commit;
`;
writeFileSync('supabase/upgrade-legacy.sql',sql);
console.log('Generated transactional legacy upgrade from '+migrations.length+' migrations.');
