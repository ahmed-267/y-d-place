import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
const names = readdirSync('supabase/migrations').filter(n=>n.endsWith('.sql')).sort();
const guard = `-- GENERATED by npm run build:database. For a NEW Supabase project only.
-- One transaction: an error rolls back the entire install. Never run on the old test project.
begin;
do $$ begin
 if exists(select 1 from information_schema.tables where table_schema='public' and table_type='BASE TABLE') then
  raise exception 'Fresh install refused: public already contains tables. Use a new empty Supabase project.';
 end if;
end $$;
`;
const body = names.map(name => `\n-- SOURCE: ${name}\n` + readFileSync(`supabase/migrations/${name}`,'utf8').replace(/^\s*(begin|commit);\s*$/gmi,'')).join('\n');
writeFileSync('supabase/install-fresh.sql',guard + body + '\ncommit;\n');
console.log(`Generated supabase/install-fresh.sql from ${names.length} migrations; existing tables are guarded.`);
