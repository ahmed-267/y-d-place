import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
 await page.goto(process.env.TEST_APP_URL || 'http://127.0.0.1:3000/',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:/try demo/i}).first().click();
 await page.getByRole('button',{name:/Owner portal/}).click();
 await page.getByRole('button',{name:'Staff',exact:true}).last().click();
 await page.getByRole('button',{name:'My Shifts',exact:true}).first().click();
 assert.equal(await page.getByRole('button',{name:/log today/i}).count(),0);
 await page.getByRole('heading',{name:'My time-off history'}).waitFor();
 await page.getByText('Time off',{exact:true}).click();
 const from=new Date(Date.now()+60*86400000).toISOString().slice(0,10);
 const to=new Date(Date.now()+62*86400000).toISOString().slice(0,10);
 await page.getByLabel('First day',{exact:true}).fill(from);
 await page.getByLabel('Last day',{exact:true}).fill(to);
 await page.getByRole('button',{name:'Submit request',exact:true}).click();
 await page.getByText('pending',{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('previsio_ops_v1:ydplace')).workShifts.filter(s=>s.kind==='leave').length),0);
 await page.getByRole('button',{name:'Manager',exact:true}).click();
 await page.getByRole('button',{name:/^Staff/}).first().click();
 await page.getByLabel('1 pending time-off requests').waitFor();
 await page.getByRole('button',{name:/Time off/i}).click();
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 await page.getByText('approved',{exact:true}).waitFor();
 await page.getByLabel('1 pending time-off requests').waitFor({state:'detached'});
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('previsio_ops_v1:ydplace')).workShifts.filter(s=>s.kind==='leave').length===3);
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('previsio_ops_v1:ydplace')).workShifts.filter(s=>s.kind==='leave').length),3);
 assert.equal(await page.getByRole('button',{name:/park ticket|parked tickets/i}).count(),0);
 await page.getByRole('button',{name:'Cashier',exact:true}).first().click();
 await page.setViewportSize({width:390,height:844});
 const menu=await page.locator('div.order-1').last().boundingBox();
 const cart=await page.locator('div.order-2').last().boundingBox();
 assert.ok(menu && cart && cart.y>=menu.y+menu.height-1,'Mobile cart must follow the menu');
 assert.deepEqual(errors,[]);
 console.log('PASS: multi-day pending request, manager approval, three leave days, reload persistence, no parked-ticket controls.');
} finally {await browser.close();}
