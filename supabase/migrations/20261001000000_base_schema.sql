create table if not exists public.businesses (
 id text primary key default gen_random_uuid()::text, owner_user_id uuid unique not null,
 name text not null, owner_name text, owner_email text, owner_phone text, venue_type text,
 country text, city text, address text, opening_hours text, currency_code text default 'EUR',
 currency_symbol text default '€', language text default 'en', setup_completed boolean default false,
 enabled_modules jsonb default '{}'::jsonb, discount_policy jsonb default '{}'::jsonb,
 brand_theme jsonb default '{}'::jsonb, categories jsonb default '[]'::jsonb
);
create table if not exists public.app_users (
 id uuid primary key, business_id text references public.businesses(id), username text not null,
 full_name text, role text not null check (role in ('owner','manager','staff')), email text,
 hourly_rate numeric, numeric_id bigint generated by default as identity
);
create table if not exists public.products (
 id bigint primary key, business_id text not null references public.businesses(id), name_en text not null,
 translations jsonb default '{}', category text, price numeric not null check(price >= 0), emoji text,
 active boolean default true, trans_key text, ingredient_links jsonb default '[]', prepared_stock_links jsonb default '[]',
 extra_ids jsonb default '[]', is_favourite boolean default false, pos_color text
);
create table if not exists public.ingredients (
 id bigint primary key, business_id text not null references public.businesses(id), name text not null,
 unit text, qty numeric not null default 0 check(qty >= 0), low_threshold numeric default 5
);
create table if not exists public.prepared_stock (
 id bigint primary key, business_id text not null references public.businesses(id), name text not null,
 portions numeric not null default 0 check(portions >= 0), low_threshold numeric default 5
);
create table if not exists public.sales (
 id text primary key, business_id text not null references public.businesses(id), subtotal numeric not null,
 payment_method text, cashier_username text, cashier_fullname text, discount_percent numeric default 0,
 discount_amount numeric default 0, tip_amount numeric default 0, tendered_cash numeric, change_given numeric,
 cash_amount numeric, card_amount numeric, status text default 'completed', void_reason text, refunded_at timestamptz,
 customer_name text, customer_phone text, customer_id text, created_at timestamptz default now(), timestamp bigint
);
create table if not exists public.sale_items (
 id bigint generated by default as identity primary key, sale_id text not null references public.sales(id) on delete cascade,
 product_id bigint, qty numeric not null check(qty > 0), unit_price numeric not null, line_total numeric not null,
 extras jsonb default '[]', name_en text, translations jsonb default '{}', note text
);
create table if not exists public.orders (
 id text primary key, business_id text not null references public.businesses(id), type text, status text,
 created_at timestamptz default now(), updated_at timestamptz default now(), scheduled_for timestamptz,
 customer_name text, customer_phone text, items jsonb default '[]', subtotal numeric, payment_method text,
 created_by_username text, created_by_fullname text, completed_at timestamptz, sale_id text,
 discount_amount numeric default 0, tip_amount numeric default 0, void_reason text, kitchen_printed_at timestamptz,
 customer_id text, source text default 'pos', table_id text, table_label text, covers integer
);
create table if not exists public.expenses (
 id text primary key default gen_random_uuid()::text, business_id text not null references public.businesses(id),
 name text, category text, amount numeric, date date, is_recurring boolean default false, frequency text, receipt_image text
);
create table if not exists public.work_shifts (
 id text primary key default gen_random_uuid()::text, business_id text not null references public.businesses(id),
 user_id bigint, username text, full_name text, date date, start_time text, end_time text,
 break_minutes numeric, total_hours numeric, notes text
);
create table if not exists public.rota_shifts (
 id text primary key, business_id text not null references public.businesses(id), username text, "userId" bigint,
 "fullName" text, date date, "startTime" text, "endTime" text, "breakMinutes" numeric, notes text
